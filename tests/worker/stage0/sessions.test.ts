import { beforeEach, expect, it } from 'vitest'
import { databaseFixture } from './database'
import { issueSession, resolveSession, rotateSession, revokeSession, revokeAllSessions, verifyCsrf } from '../../../src/cloudflare/stage0/auth/sessions'

let f: Awaited<ReturnType<typeof databaseFixture>>
beforeEach(async () => { f = await databaseFixture() })
it('stores only token digests and resolves a verified account without leaking secrets in audit', async () => {
  const issued = await issueSession(f.ctx, { accountId: 'a', method: 'password' }, 'browser')
  expect(issued.token).toMatch(/^[A-Za-z0-9_-]{43}$/)
  expect(issued.csrfToken).toMatch(/^[A-Za-z0-9_-]{43}$/)
  const row = await f.execute('SELECT * FROM sessions WHERE id=?', issued.principal.sessionId).first()
  expect(row?.token_digest).toMatch(/^[a-f0-9]{64}$/)
  expect(JSON.stringify(row)).not.toContain(issued.token)
  expect(JSON.stringify(await f.execute('SELECT * FROM audit_events').all())).not.toContain(issued.token)
  expect(await resolveSession(f.ctx, issued.token, 'browser')).toMatchObject({ accountId: 'a', method: 'password', assurance: 'authenticated' })
  expect(await verifyCsrf(f.ctx, issued.principal, issued.csrfToken!)).toBe(true)
  const other = await issueSession(f.ctx, { accountId: 'a', method: 'password' }, 'browser')
  expect(await verifyCsrf(f.ctx, other.principal, issued.csrfToken!)).toBe(false)
  await expect(resolveSession(f.ctx, issued.token, 'desktop')).rejects.toMatchObject({ code: 'unauthenticated' })
  await expect(resolveSession(f.ctx, 'bad-token', 'browser')).rejects.toMatchObject({ code: 'unauthenticated' })
})
it('expires exactly at the absolute deadline and rejects disabled accounts', async () => {
  const issued = await issueSession(f.ctx, { accountId: 'a', method: 'passkey' }, 'desktop')
  expect(issued.csrfToken).toBeNull()
  await f.execute("UPDATE accounts SET disabled_at=1 WHERE id='a'").run()
  await expect(resolveSession(f.ctx, issued.token, 'desktop')).rejects.toMatchObject({ code: 'unauthenticated' })
  await expect(issueSession(f.ctx, { accountId: 'a', method: 'passkey' }, 'desktop')).rejects.toMatchObject({ code: 'unauthenticated' })
  await f.execute("UPDATE accounts SET disabled_at=NULL WHERE id='a'").run()
  f.advance(43_200_000)
  await expect(resolveSession(f.ctx, issued.token, 'desktop')).rejects.toMatchObject({ code: 'unauthenticated' })
})
it('unverified accounts receive enrollment-only sessions and cannot claim passkey assurance', async () => {
  await f.execute("UPDATE accounts SET email_verified_at=NULL WHERE id='d'").run()
  const issued = await issueSession(f.ctx, { accountId: 'd', method: 'password' }, 'browser')
  expect(issued.principal.assurance).toBe('enrollment')
  await expect(issueSession(f.ctx, { accountId: 'd', method: 'passkey' }, 'browser')).rejects.toMatchObject({ code: 'forbidden' })
})
it('rotates once without extending lifetime or refreshing passkey authentication time', async () => {
  const old = await issueSession(f.ctx, { accountId: 'a', method: 'passkey' }, 'browser')
  const before = await f.execute('SELECT expires_at FROM sessions WHERE id=?', old.principal.sessionId).first('expires_at')
  f.advance(60_000)
  const results = await Promise.allSettled([rotateSession(f.ctx, old.principal), rotateSession(f.ctx, old.principal)])
  expect(results.filter(result => result.status === 'fulfilled')).toHaveLength(1)
  const winner = results.find(result => result.status === 'fulfilled')!
  if (winner.status !== 'fulfilled') throw new Error('Missing rotation result')
  expect(winner.value.principal.authenticatedAt).toBe(old.principal.authenticatedAt)
  expect(await f.execute('SELECT expires_at FROM sessions WHERE id=?', winner.value.principal.sessionId).first('expires_at')).toBe(before)
  await expect(resolveSession(f.ctx, old.token, 'browser')).rejects.toMatchObject({ code: 'unauthenticated' })
  expect((await resolveSession(f.ctx, winner.value.token, 'browser')).accountId).toBe('a')
})
it('revokes own sessions and all transports without allowing another account to revoke them', async () => {
  const a = await issueSession(f.ctx, { accountId: 'a', method: 'password' }, 'browser')
  const desktop = await issueSession(f.ctx, { accountId: 'a', method: 'passkey' }, 'desktop')
  const b = await issueSession(f.ctx, { accountId: 'b', method: 'password' }, 'browser')
  await expect(revokeSession(f.ctx, b.principal, a.principal.sessionId)).rejects.toMatchObject({ code: 'not_found' })
  await revokeSession(f.ctx, a.principal, desktop.principal.sessionId)
  await expect(resolveSession(f.ctx, desktop.token, 'desktop')).rejects.toMatchObject({ code: 'unauthenticated' })
  await revokeAllSessions(f.ctx, a.principal)
  await expect(resolveSession(f.ctx, a.token, 'browser')).rejects.toMatchObject({ code: 'unauthenticated' })
  expect((await resolveSession(f.ctx, b.token, 'browser')).accountId).toBe('b')
})
it('binds federated sessions to the exact account, identity, protocol and connection version', async () => {
  await f.execute("INSERT INTO identity_connections(id,protocol,provider,issuer,client_id,created_at) VALUES('google','oidc','google','https://accounts.google.com','fixture',1)").run()
  await f.execute("INSERT INTO external_identities(id,account_id,connection_id,issuer,subject,created_at) VALUES('identity-a','a','google','https://accounts.google.com','fixture-subject',1)").run()
  await expect(issueSession(f.ctx, { accountId: 'b', method: 'oidc', externalIdentityId: 'identity-a' }, 'browser')).rejects.toMatchObject({ code: 'unauthenticated' })
  await expect(issueSession(f.ctx, { accountId: 'a', method: 'saml', externalIdentityId: 'identity-a' }, 'browser')).rejects.toMatchObject({ code: 'unauthenticated' })
  const issued = await issueSession(f.ctx, { accountId: 'a', method: 'oidc', externalIdentityId: 'identity-a' }, 'browser')
  expect(issued.principal).toMatchObject({ assurance: 'authenticated', connectionId: 'google', connectionVersion: 1 })
  await f.execute("UPDATE identity_connections SET version=2,enabled=0 WHERE id='google'").run()
  await expect(resolveSession(f.ctx, issued.token, 'browser')).rejects.toMatchObject({ code: 'unauthenticated' })
  await f.execute("UPDATE identity_connections SET version=3,enabled=1 WHERE id='google'").run()
  await expect(resolveSession(f.ctx, issued.token, 'browser')).rejects.toMatchObject({ code: 'unauthenticated' })
})
it('rolls back session revocation if its audit write fails', async () => {
  const issued = await issueSession(f.ctx, { accountId: 'a', method: 'password' }, 'browser')
  f.ctx.ids.next = () => 'duplicate-audit'
  await f.execute("INSERT INTO audit_events(id,actor_account_id,action,resource_id,request_id,created_at) VALUES('duplicate-audit','a','session.issue','fixture','fixture',1)").run()
  await expect(revokeAllSessions(f.ctx, issued.principal)).rejects.toThrow()
  expect((await resolveSession(f.ctx, issued.token, 'browser')).accountId).toBe('a')
  expect(await f.execute('SELECT count(*) AS n FROM stage0_guards').first('n')).toBe(0)
})
it('does not revive old sessions after an account is disabled and re-enabled', async () => {
  const issued = await issueSession(f.ctx,{accountId:'a',method:'password'},'browser')
  await f.execute("UPDATE accounts SET disabled_at=1 WHERE id='a'").run()
  await f.execute("UPDATE accounts SET disabled_at=NULL WHERE id='a'").run()
  await expect(resolveSession(f.ctx,issued.token,'browser')).rejects.toMatchObject({code:'unauthenticated'})
})
it('prevents modifying session assurance or unrevoking a retired session in place', async () => {
  const issued = await issueSession(f.ctx,{accountId:'a',method:'password'},'browser')
  await expect(f.execute("UPDATE sessions SET assurance='passkey',passkey_verified_at=? WHERE id=?",f.ctx.clock.now(),issued.principal.sessionId).run()).rejects.toThrow()
  await revokeSession(f.ctx,issued.principal,issued.principal.sessionId)
  await expect(f.execute('UPDATE sessions SET revoked_at=NULL WHERE id=?',issued.principal.sessionId).run()).rejects.toThrow()
})
it('does not revive external-identity sessions after disable and re-enable', async () => {
  await f.execute("INSERT INTO identity_connections(id,protocol,provider,issuer,client_id,created_at) VALUES('google','oidc','google','https://accounts.google.com','fixture',1)").run()
  await f.execute("INSERT INTO external_identities(id,account_id,connection_id,issuer,subject,created_at) VALUES('identity-a','a','google','https://accounts.google.com','subject-a',1)").run()
  const session = await issueSession(f.ctx,{accountId:'a',method:'oidc',externalIdentityId:'identity-a'},'browser')
  await f.execute("UPDATE external_identities SET disabled_at=1,version=2 WHERE id='identity-a'").run()
  await f.execute("UPDATE external_identities SET disabled_at=NULL,version=3 WHERE id='identity-a'").run()
  await expect(resolveSession(f.ctx,session.token,'browser')).rejects.toMatchObject({code:'unauthenticated'})
})
