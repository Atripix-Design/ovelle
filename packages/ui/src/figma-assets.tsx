/** Original Figma SVGs in their exported Light and Dark colors. Native dimensions are retained. */
export function FigmaAsset({ name, darkName, className, ...props }: Omit<ImgHTMLAttributes<HTMLImageElement>, "src" | "width" | "height"> & { name: string; darkName?: string }) {
  if (!assets[name] || (darkName && !assets[darkName])) throw new Error(`Missing Figma asset: ${name} / ${darkName}`);
  const image = (file: string, theme?: string) => <img alt="" aria-hidden="true" {...props} className={[className, theme].filter(Boolean).join(" ") || undefined} src={assets[file]} />;
  return darkName ? <>{image(name, "ov-asset-light")}{image(darkName, "ov-asset-dark")}</> : image(name);
}
